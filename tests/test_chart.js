"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), vm = require("node:vm");
const context = {}; vm.createContext(context);
vm.runInContext(fs.readFileSync("traid_ai/web/chart.js", "utf8") + "\nglobalThis.ChartViewport = ChartViewport;", context);
const viewport = new context.ChartViewport();
const points = (end = 60) => Array.from({length:end+1}, (_,i) => ({time:new Date(i*60000).toISOString(),price:100+i}));
viewport.update(points(), "first");
assert.equal(viewport.start, 0); assert.equal(viewport.end, 3600000);
viewport.preset(900000); assert.equal(viewport.start, 2700000);
viewport.update(points(61), "first"); assert.equal(viewport.start, 2760000); assert.equal(viewport.follow, true);
viewport.pan(-900000); const start = viewport.start, end = viewport.end;
viewport.update(points(65), "first"); assert.equal(viewport.start, start); assert.equal(viewport.end, end); assert.equal(viewport.follow, false);
viewport.pan(-99999999); assert.equal(viewport.start, viewport.min);
viewport.pan(99999999); assert.equal(viewport.end, viewport.max);
viewport.zoom(.5, 1); assert.equal(viewport.end, viewport.max);
const span = viewport.end - viewport.start;
viewport.latest(); viewport.update(points(70), "first"); assert.equal(viewport.end, 4200000); assert.equal(viewport.end-viewport.start, span);
for (let i = 0; i < 100; i++) viewport.zoom(.1, .5);
assert(viewport.end - viewport.start >= 14000 - .001);
viewport.zoom(1e9); assert.equal(viewport.start, viewport.min); assert.equal(viewport.end, viewport.max);
viewport.update(points(5), "second"); assert.equal(viewport.follow, true); assert.equal(viewport.start, 0); assert.equal(viewport.end, 300000);
viewport.update([], null); assert.equal(viewport.start, 0); assert.equal(viewport.end, 0);
viewport.zoom(.5); viewport.pan(99); assert.equal(viewport.end, 0);
viewport.update(points(0), "single"); viewport.zoom(.5); assert.equal(viewport.start, viewport.end);
console.log("График: масштаб, границы, следование, просмотр истории, автообновление и пустые данные — OK");
